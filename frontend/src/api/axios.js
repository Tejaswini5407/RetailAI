import axios from 'axios';

const API_BASE_URL = import.meta.env.VITE_API_BASE_URL || 'http://localhost:8080';

const apiClient = axios.create({
  baseURL: API_BASE_URL,
  headers: {
    'Content-Type': 'application/json',
  },
});

apiClient.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem('retailai_token');
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => Promise.reject(error)
);

apiClient.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response && error.response.status === 401) {
      // Clear token on 401 if unauthenticated
      if (localStorage.getItem('retailai_token')) {
        localStorage.removeItem('retailai_token');
        localStorage.removeItem('retailai_user');
        window.dispatchEvent(new Event('retailai_auth_expired'));
      }
    }
    return Promise.reject(error);
  }
);

export default apiClient;
